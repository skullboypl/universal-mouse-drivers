/**
 * Generate the local OpenMouse product-image map from explicitly approved,
 * locally staged assets. This intentionally does not scrape image search or
 * copy files from upstream's device bucket: upstream documents those renders
 * as third-party artwork whose redistribution terms need separate approval.
 *
 * To add an asset, stage it under public/devices/openmouse/approved/ and add
 * its exact model keys and licensing/provenance fields to
 * scripts/openmouse-product-assets.approved.json. The script verifies every
 * source file and model key before generating the map and provenance record.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptDir = path.dirname(fileURLToPath(import.meta.url))
const webRoot = path.resolve(scriptDir, '..')
const catalogPath = path.join(webRoot, 'src/devices/openmouse/catalog.generated.ts')
const approvedPath = path.join(scriptDir, 'openmouse-product-assets.approved.json')
const mapPath = path.join(webRoot, 'src/devices/openmouse/productImages.generated.ts')
const provenancePath = path.join(webRoot, 'src/devices/openmouse/product-images.provenance.json')
const upstreamRevision = '02d7b178664f6fb6799977375003b5a5c9b69417'

function readCatalog() {
  const source = fs.readFileSync(catalogPath, 'utf8')
  const entries = []
  const re = /\{\s*id:\s*"([^"]+)",\s*brand:\s*"([^"]+)",\s*brandSlug:\s*"([^"]+)",\s*slug:\s*"([^"]+)",\s*name:\s*"([^"]+)",[\s\S]*?hasProductName:\s*(true|false)/g
  for (const match of source.matchAll(re)) {
    entries.push({ id: match[1], brand: match[2], brandSlug: match[3], slug: match[4], name: match[5] })
  }
  if (!entries.length) throw new Error(`No catalog entries found in ${catalogPath}`)
  return entries
}

function safeLocalFile(localPath) {
  if (typeof localPath !== 'string' || !localPath.startsWith('public/devices/openmouse/approved/')) {
    throw new Error(`Asset path must be under public/devices/openmouse/approved/: ${localPath}`)
  }
  const absolute = path.resolve(webRoot, localPath)
  const allowedRoot = path.resolve(webRoot, 'public/devices/openmouse/approved') + path.sep
  if (!absolute.startsWith(allowedRoot)) throw new Error(`Asset path escapes approved directory: ${localPath}`)
  if (!fs.existsSync(absolute) || !fs.statSync(absolute).isFile() || fs.statSync(absolute).size < 128) {
    throw new Error(`Approved local asset is missing or too small: ${localPath}`)
  }
  if (!/\.(png|jpe?g|webp|svg)$/i.test(localPath)) throw new Error(`Unsupported image type: ${localPath}`)
  return absolute
}

function main() {
  const catalog = readCatalog()
  const approval = JSON.parse(fs.readFileSync(approvedPath, 'utf8'))
  if (approval.schemaVersion !== 1 || !Array.isArray(approval.assets)) {
    throw new Error(`${approvedPath} must contain schemaVersion: 1 and an assets array`)
  }

  const knownKeys = new Set(catalog.map((entry) => `${entry.brandSlug}/${entry.slug}`))
  const productImages = {}
  const upstreamImages = {}
  const records = []
  for (const asset of approval.assets) {
    if (asset.redistributionApproved !== true) throw new Error(`Redistribution is not approved for ${asset.localPath}`)
    if (!['verified-product', 'upstream-model'].includes(asset.kind)) throw new Error(`Invalid asset kind for ${asset.localPath}: ${asset.kind}`)
    for (const field of ['sourceUrl', 'sourceRevision', 'license', 'licenseUrl', 'attribution', 'localPath']) {
      if (typeof asset[field] !== 'string' || !asset[field].trim()) throw new Error(`Missing ${field} for ${asset.localPath || 'approved asset'}`)
    }
    const localPath = safeLocalFile(asset.localPath)
    if (!Array.isArray(asset.modelKeys) || !asset.modelKeys.length) throw new Error(`No modelKeys for ${asset.localPath}`)
    for (const modelKey of asset.modelKeys) {
      if (!knownKeys.has(modelKey)) throw new Error(`Unknown catalog model key ${modelKey} in ${asset.localPath}`)
      const target = asset.kind === 'upstream-model' ? upstreamImages : productImages
      if (productImages[modelKey] || upstreamImages[modelKey]) throw new Error(`Duplicate image mapping for ${modelKey}`)
      target[modelKey] = `/${asset.localPath.slice('public/'.length).replaceAll(path.sep, '/')}`
    }
    records.push({
      modelKeys: [...asset.modelKeys],
      kind: asset.kind,
      imagePath: (asset.kind === 'upstream-model' ? upstreamImages : productImages)[asset.modelKeys[0]],
      sourceUrl: asset.sourceUrl,
      sourceRevision: asset.sourceRevision,
      license: asset.license,
      licenseUrl: asset.licenseUrl,
      attribution: asset.attribution,
      sha256: asset.sha256 || null,
      fileBytes: fs.statSync(localPath).size,
    })
  }

  const mapSource = `/** Generated by scripts/fetch-openmouse-product-images.mjs. */\nexport const OPENMOUSE_PRODUCT_IMAGES: Record<string, string> = ${JSON.stringify(productImages, null, 2)}\nexport const OPENMOUSE_UPSTREAM_MODEL_IMAGES: Record<string, string> = ${JSON.stringify(upstreamImages, null, 2)}\n\nexport function openMouseProductImagePath(brandSlug: string, slug?: string): string | undefined {\n  return slug ? OPENMOUSE_PRODUCT_IMAGES[\`${'${brandSlug}'}/${'${slug}'}\`] : undefined\n}\n\nexport function openMouseUpstreamModelImagePath(brandSlug: string, slug?: string): string | undefined {\n  return slug ? OPENMOUSE_UPSTREAM_MODEL_IMAGES[\`${'${brandSlug}'}/${'${slug}'}\`] : undefined\n}\n`
  fs.writeFileSync(mapPath, mapSource)
  fs.writeFileSync(provenancePath, `${JSON.stringify({
    schemaVersion: 1,
    upstream: {
      repository: 'https://github.com/OpenMouse-Project/openmouse',
      revision: upstreamRevision,
      mappingFile: `https://github.com/OpenMouse-Project/openmouse/blob/${upstreamRevision}/src/ui/device-images.ts`,
      mappingMethod: 'device-reported display name rules; image bytes are hosted in the upstream Cloudflare R2 bucket, outside the repository',
      license: 'AGPL-3.0 applies to the upstream program; the upstream artwork README identifies model renders as third-party assets with separate, often unconfirmed redistribution terms',
      artworkReadme: `https://github.com/OpenMouse-Project/openmouse/blob/${upstreamRevision}/public/devices/README.md`,
      importedUpstreamAssets: records.filter((record) => record.sourceUrl.includes('openmouse-devices')).length,
      note: 'Only assets with explicit redistribution approval are emitted into the local product-image map. Upstream-listed renders are not automatically redistributable.',
    },
    catalogEntryCount: catalog.length,
    mappedModelCount: Object.keys(productImages).length + Object.keys(upstreamImages).length,
    assets: records,
  }, null, 2)}\n`)

  console.log(`Validated ${catalog.length} catalog entries; mapped ${Object.keys(productImages).length} approved product images and ${Object.keys(upstreamImages).length} approved upstream graphics.`)
  console.log(`Wrote ${path.relative(webRoot, mapPath)} and ${path.relative(webRoot, provenancePath)}`)
}

main()
